class JobTagMapper:
    POLARIZ = 'POLARIZ_LR'
    SP = 'SP'
    POLARIZ_FF = 'POLARIZ_FF'
    OPT = 'OPT'

    _tags = {
        POLARIZ: [],
        SP: [],
        POLARIZ_FF: [],
        OPT: []
    }

    @classmethod
    def get_unique_key(cls, key: str) -> str:
        key_lower = key.lower().strip()
        found = []
        for canonical, aliases in cls._tags.items():
            all_keys = [ x.lower().strip() for x in [canonical] + aliases ]
            if key_lower in all_keys:
                found.append(canonical.upper())
        if len(found) == 0:
            raise Exception(f"Internal problem: cannot interpret jobtag '{key}'")
        elif len(found) == 1:
            return found[0].upper()
        else:
            raise Exception(f"Coding error: '{key}' mapped on multiple tags! {found}")

def psi4_input_single(
        job: psi4_job
):
    """ Create an single psi4 input file """

    preamble, dump_storage_var=make_preamble(job)


    # Creation of the molecul, jobname=Nonee
    geom=job.geom
    molecule_lines, monomer_string=geom.molecule_lines(job.var_names.molecule_name, 
        symm=True if not job.jobtag in [job._available_job_tags.OPT, job._available_job_tags.POLARIZ_FF] else False )
    job.var_names.molecule_string=monomer_string

    method_section_lines=job.method_lines()


    # Get the job
    storage_var=job.var_names.storage

    unique_tag=JobTagMapper.get_unique_key(job.jobtag)

    if unique_tag == JobTagMapper.POLARIZ:
        job_lines, func_lines = generate_pol_lr_job_lines(job)
    elif unique_tag == JobTagMapper.SP:
        job_lines = get_single_point(job)
        func_lines=[]
    elif unique_tag == JobTagMapper.POLARIZ_FF:
        from .job_lines.pol_ff import options
        opts=options(do_moments=job.do_moments)
        job_lines, func_lines = generate_pol_ff_job_lines(job, opts )
    elif unique_tag == JobTagMapper.OPT:
        job_lines = optimization(job)
        func_lines=[]
    else:
        raise Exception(f"Job tag not handled yet: {unique_tag}")

    job_lines = [
        '# Starting job',
        f"def run_job():",
        *[ind+x for x in job_lines],
        f"",
        f"# Execute the job",
        f"try:",
        ind+f"start_{unique_tag.lower()}=time.time()",
        ind+f"run_job()",
        *[ ind+x for x in store(job,('about_the_run','timings',f"Total Time for {unique_tag}"), f"start_{unique_tag.lower()}-time.time()")],
        f"finally: clean() # I allways want to clean up the scratch",
        # except KeyboardInterrupt as ex: # if a worker is killed then clean up the scratch!",
        # d+f"clean(); raise KeyboardInterrupt()",
        # except Exception as ex: # cleanup and re-raise original exception",
        # d+f"clean(); raise ex
    ]

    final_lines=[
        f"# Dump storage at the end of the run",
        f"try:",
        ind+f"{dump_storage_var}()",
        f"except Exception as ex: raise Exception(f\"Could not dump storage: {{ex}}\")",
        f"finally: clean()"
    ]

    content= [  *preamble, '',
                *molecule_lines, '',
                '#### FUNCTIONS (could be moved to other file but this way its implicity portable [no need to copy multiple files])',
                *func_lines, '#### END FUNCTIONS', '',
                *method_section_lines, '',
                *job_lines, '',
                *final_lines,
    ]

    for x in content:
        assert isinstance(x,str), f"Not a string {x}"
    with open(job.files.input,'w') as wr:
        wr.write('\n'.join(content))
    return job